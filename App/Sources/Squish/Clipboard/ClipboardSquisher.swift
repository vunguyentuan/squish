import AppKit
import Carbon.HIToolbox
import Observation
import UniformTypeIdentifiers

/// Optimizes the image on the clipboard in place (⌃⌥⌘V), e.g. a screenshot before pasting it
/// into Slack or GitHub. The image keeps its type (PNG stays PNG, JPEG stays JPEG) so every app
/// can still paste it. Copied files are optimized like any dropped file.
///
/// With "Optimize copied images automatically" on, the same happens to every image that is
/// copied, without the shortcut.
@Observable
final class ClipboardSquisher {
    static let shared = ClipboardSquisher()
    static let shortcut = "⌃⌥⌘V"

    /// Added to everything Squish writes, so the watcher doesn't pick up its own output.
    nonisolated static let optimizedMarker = NSPasteboard.PasteboardType("dev.squish.optimized")

    private(set) var isWorking = false
    private var hotKey: HotKey?
    private var watcher: Timer?
    private var lastChangeCount = 0

    func updateHotKey() {
        hotKey = nil
        guard Preferences.shared.clipboardHotKey else { return }
        hotKey = HotKey(keyCode: kVK_ANSI_V, modifiers: controlKey | optionKey | cmdKey) { [weak self] in
            self?.squish()
        }
    }

    /// Starts or stops watching the clipboard to match the preference. There is no change
    /// notification for the pasteboard, so this polls `changeCount`, which is cheap.
    func updateWatcher() {
        watcher?.invalidate()
        watcher = nil
        guard Preferences.shared.clipboardAutoOptimize else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkForNewImage() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        watcher = timer
    }

    private func checkForNewImage() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard !isWorking,
              let items = pasteboard.pasteboardItems, items.count == 1,
              Self.shouldOptimizeAutomatically(types: items[0].types)
        else { return }
        squishCopiedImage(on: pasteboard, automatic: true)
    }

    /// Only a single copied image, never files (those would be changed on disk), and never
    /// anything marked as private or temporary by the nspasteboard.org conventions.
    nonisolated static func shouldOptimizeAutomatically(types: [NSPasteboard.PasteboardType]) -> Bool {
        let skip: Set<NSPasteboard.PasteboardType> = [
            optimizedMarker,
            .fileURL,
            NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
            NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
            NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        ]
        guard !types.contains(where: skip.contains) else { return false }
        return types.contains(where: imageTypes.contains)
    }

    /// Image types Squish replaces with the optimized image, so apps can't paste the original.
    /// Includes the legacy names some apps still write next to the UTIs.
    nonisolated static let imageTypes: Set<NSPasteboard.PasteboardType> = [
        .png, .tiff, NSPasteboard.PasteboardType(UTType.jpeg.identifier),
        NSPasteboard.PasteboardType("Apple PNG pasteboard type"),
        NSPasteboard.PasteboardType("NeXT TIFF v4.0 pasteboard type"),
    ]

    func squish() {
        guard !isWorking else { return }
        let pasteboard = NSPasteboard.general

        let files = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
        if !files.isEmpty {
            let count = OptimizerStore.shared.add(files).map { OptimizerStore.shared.jobs(in: $0).count } ?? 0
            ClipboardHUD.show(count > 0 ? "Optimizing \(Fmt.items(count)) from the clipboard" : "No images in the copied files")
            return
        }

        squishCopiedImage(on: pasteboard, automatic: false)
    }

    /// In automatic mode nothing is shown unless the image got smaller, and the other types on
    /// the clipboard (text, HTML, an app's own format) are kept so pasting still works everywhere.
    private func squishCopiedImage(on pasteboard: NSPasteboard, automatic: Bool) {
        guard let (data, format) = Self.image(on: pasteboard) else {
            if !automatic {
                NSSound.beep()
                ClipboardHUD.show("No image on the clipboard")
            }
            return
        }
        let otherData: [(NSPasteboard.PasteboardType, Data)] = automatic
            ? (pasteboard.pasteboardItems?.first?.types ?? [])
                // dyn.* types are legacy aliases, often of the original image.
                .filter { !Self.imageTypes.contains($0) && !$0.rawValue.hasPrefix("dyn.") }
                .compactMap { type in pasteboard.data(forType: type).map { (type, $0) } }
            : []
        isWorking = true
        let changeCount = pasteboard.changeCount
        var options = Preferences.shared.options(for: format)
        // Pasting needs a type every app accepts, so the format never changes here.
        options.output = .original

        Task {
            let result = await Task.detached(priority: .userInitiated) { [data, format, options] in
                Self.optimize(data, format: format, options: options)
            }.value
            isWorking = false
            guard let result else {
                if !automatic { ClipboardHUD.show("Couldn't optimize the clipboard image") }
                return
            }
            guard result.count < data.count else {
                if !automatic { ClipboardHUD.show("Clipboard image is already optimal") }
                return
            }
            // Something else was copied while we worked: don't clobber it.
            guard pasteboard.changeCount == changeCount else { return }
            let imageType = format == .jpeg ? NSPasteboard.PasteboardType(UTType.jpeg.identifier) : .png
            pasteboard.clearContents()
            pasteboard.declareTypes([imageType] + otherData.map(\.0) + [Self.optimizedMarker], owner: nil)
            pasteboard.setData(result, forType: imageType)
            for (type, value) in otherData { pasteboard.setData(value, forType: type) }
            pasteboard.setData(Data(), forType: Self.optimizedMarker)
            lastChangeCount = pasteboard.changeCount
            let saved = Int64(data.count - result.count)
            LifetimeStats.shared.record(saved: saved)
            let fraction = Double(saved) / Double(data.count)
            ClipboardHUD.show("Clipboard image \(Fmt.bytes(Int64(data.count))) → \(Fmt.bytes(Int64(result.count))) (−\(Fmt.percent(fraction)))")
        }
    }

    /// PNG or JPEG bytes from the pasteboard; TIFF (what many apps copy) becomes PNG.
    private static func image(on pasteboard: NSPasteboard) -> (Data, ImageFormat)? {
        if let png = pasteboard.data(forType: .png) { return (png, .png) }
        if let jpeg = pasteboard.data(forType: NSPasteboard.PasteboardType(UTType.jpeg.identifier)) { return (jpeg, .jpeg) }
        if let tiff = pasteboard.data(forType: .tiff),
           let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
            return (png, .png)
        }
        return nil
    }

    nonisolated static func optimize(_ data: Data, format: ImageFormat, options: OptimizeOptions) -> Data? {
        let fm = FileManager.default
        let stem = "squish-clipboard-\(UUID().uuidString)"
        let input = fm.temporaryDirectory.appending(path: "\(stem).\(format.fileExtension)")
        let output = fm.temporaryDirectory.appending(path: "\(stem)-out.\(format.fileExtension)")
        defer {
            try? fm.removeItem(at: input)
            try? fm.removeItem(at: output)
        }
        do {
            try data.write(to: input)
        } catch {
            return nil
        }
        let result = Engine.optimize(input: input, output: output, options: options)
        switch result.status {
        case .optimized: return try? Data(contentsOf: output)
        case .alreadyOptimal: return data
        case .failed: return nil
        }
    }
}
